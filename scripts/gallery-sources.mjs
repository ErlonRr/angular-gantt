#!/usr/bin/env node
// Writes the code samples of the examples gallery: apps/demo-kit/src/gallery/sources/*.generated.ts.
//
//   node scripts/gallery-sources.mjs              write the files (pnpm gallery:sources)
//   node scripts/gallery-sources.mjs --check      fail when they are out of date (pnpm gallery:check, CI)
//   node scripts/gallery-sources.mjs --complete   also fail while a case lacks a file in a framework
//
// For every case of the catalog (CASE_IDS in apps/demo-kit/src/gallery/catalog.ts) it reads the case
// directory of each framework app and the shared case module:
//
//   angular  apps/demo-angular/src/app/gallery/cases/<id>/   main file <id>-example.component.ts
//   vanilla  apps/demo-vanilla/src/gallery/cases/<id>/        main file <id>.ts
//   react    apps/demo-react/src/gallery/cases/<id>/          main file <Pascal>Example.tsx
//   vue      apps/demo-vue/src/gallery/cases/<id>/            main file <Pascal>Example.vue
//   svelte   apps/demo-svelte/src/gallery/cases/<id>/         main file <Pascal>Example.svelte
//   shared   apps/demo-kit/src/gallery/cases/<id>.ts          (the "Shared data" tab)
//
// Every file of a case directory is included (main file first, then by path; tests and dotfiles
// skipped). The output is deterministic (sorted, LF line ends) and carries a "generated" header; a
// case directory whose name is not a catalog id is an error. The Angular site imports the samples
// (esbuild has no `?raw`), and every app's "Shared data" tab reads them.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DEFAULT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Framework → its case tree, in the order of the gallery tabs. */
export const FRAMEWORK_TREES = {
  angular: 'apps/demo-angular/src/app/gallery/cases',
  vanilla: 'apps/demo-vanilla/src/gallery/cases',
  react: 'apps/demo-react/src/gallery/cases',
  vue: 'apps/demo-vue/src/gallery/cases',
  svelte: 'apps/demo-svelte/src/gallery/cases',
};
export const SHARED_DIR = 'apps/demo-kit/src/gallery/cases';
export const CATALOG = 'apps/demo-kit/src/gallery/catalog.ts';
export const OUT_DIR = 'apps/demo-kit/src/gallery/sources';

const pascal = id =>
  id
    .split('-')
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

/** The main file of a case in each framework (required by `--complete`). */
export const MAIN_FILE = {
  angular: id => `${id}-example.component.ts`,
  vanilla: id => `${id}.ts`,
  react: id => `${pascal(id)}Example.tsx`,
  vue: id => `${pascal(id)}Example.vue`,
  svelte: id => `${pascal(id)}Example.svelte`,
};

const LANGS = {
  '.ts': 'ts',
  '.tsx': 'tsx',
  '.js': 'js',
  '.mjs': 'js',
  '.vue': 'vue',
  '.svelte': 'svelte',
  '.html': 'html',
  '.css': 'css',
  '.scss': 'scss',
};
const SKIPPED = /\.(spec|test)\.[a-z]+$/;

const HEADER = [
  '// Generated by scripts/gallery-sources.mjs from the gallery case files: do not edit.',
  '// After changing a case run `pnpm gallery:sources` (CI checks it with `pnpm gallery:check`).',
].join('\n');

const byPath = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const lf = text => text.replace(/\r\n?/g, '\n');

/** The case ids of the catalog, in catalog order (read from `CASE_IDS`, without running TypeScript). */
export function readCaseIds(root = DEFAULT_ROOT) {
  const source = readFileSync(join(root, CATALOG), 'utf8');
  const list = /export const CASE_IDS = \[([\s\S]*?)\] as const/.exec(source);
  if (!list) throw new Error(`${CATALOG}: no \`export const CASE_IDS = [...] as const\``);
  return [...list[1].matchAll(/'([^']+)'/g)].map(m => m[1]);
}

/** Files under `dir` (paths relative to it, `/`-separated, sorted), sources only. */
function listFiles(dir, prefix = '') {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...listFiles(join(dir, entry.name), rel));
    else if (entry.isFile() && LANGS[extname(entry.name)] && !SKIPPED.test(entry.name)) out.push(rel);
  }
  return out.sort(byPath);
}

const sourceFile = (file, path) => ({ file, lang: LANGS[extname(path)], code: lf(readFileSync(path, 'utf8')) });

function printFiles(files) {
  return files
    .map(f =>
      [
        '    {',
        `      file: ${JSON.stringify(f.file)},`,
        `      lang: ${JSON.stringify(f.lang)},`,
        `      code: ${JSON.stringify(f.code)},`,
        '    },',
      ].join('\n'),
    )
    .join('\n');
}

function printCase(sources) {
  const lines = [HEADER, "import type { CaseSources } from './types';", '', 'const sources: CaseSources = {'];
  for (const [key, files] of Object.entries(sources)) lines.push(`  ${key}: [`, printFiles(files), '  ],');
  lines.push('};', '', 'export default sources;', '');
  return lines.join('\n');
}

function printIndex(ids, coverage) {
  const lines = [
    HEADER,
    "import type { CaseId, GalleryFramework } from '../catalog';",
    "import type { CaseSources } from './types';",
    '',
    '/** The code samples of each case, loaded on demand (one chunk per case). */',
    'export const CASE_SOURCES: Readonly<Record<CaseId, () => Promise<CaseSources>>> = {',
    ...ids.map(id => `  ${JSON.stringify(id)}: () => import('./${id}.generated').then(m => m.default),`),
    '};',
    '',
    '/** The frameworks that have their own file for each case (the others draw the shared data generically). */',
    'export const CASE_COVERAGE: Readonly<Record<CaseId, readonly GalleryFramework[]>> = {',
    ...ids.map(id => `  ${JSON.stringify(id)}: [${coverage[id].map(fw => JSON.stringify(fw)).join(', ')}],`),
    '};',
    '',
  ];
  return lines.join('\n');
}

/**
 * Computes the generated files and compares them with the disk.
 *
 * @returns `outputs` (path relative to the root → content), `changed` (outputs that differ from the
 * disk), `stale` (old `*.generated.ts` files no case produces), `missing` (`<framework>/<main file>`
 * of cases without their file), `errors` (unknown case directories, missing shared modules). With
 * `write`, writes the changed outputs and removes the stale files.
 */
export function runGenerator({ root = DEFAULT_ROOT, write = false } = {}) {
  const ids = readCaseIds(root);
  const known = new Set(ids);
  const errors = [];
  const missing = [];
  const outputs = new Map();
  const coverage = Object.fromEntries(ids.map(id => [id, []]));

  for (const tree of Object.values(FRAMEWORK_TREES)) {
    const dir = join(root, tree);
    if (!existsSync(dir)) continue;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory() && !entry.name.startsWith('.') && !known.has(entry.name)) {
        errors.push(`${tree}/${entry.name}: not a case id of ${CATALOG}`);
      }
    }
  }

  for (const id of ids) {
    const sources = {};
    for (const [fw, tree] of Object.entries(FRAMEWORK_TREES)) {
      const dir = join(root, tree, id);
      const main = MAIN_FILE[fw](id);
      const files = existsSync(dir) ? listFiles(dir) : [];
      if (!files.includes(main)) missing.push(`${fw}/${id}/${main}`);
      if (files.length === 0) continue;
      const ordered = files.includes(main) ? [main, ...files.filter(f => f !== main)] : files;
      sources[fw] = ordered.map(f => sourceFile(f, join(dir, f)));
      if (files.includes(main)) coverage[id].push(fw);
    }
    const shared = join(root, SHARED_DIR, `${id}.ts`);
    if (existsSync(shared)) sources.shared = [sourceFile(`demo-kit/gallery/cases/${id}.ts`, shared)];
    else {
      errors.push(`${SHARED_DIR}/${id}.ts: missing (every case has a shared module)`);
      sources.shared = [];
    }
    outputs.set(`${OUT_DIR}/${id}.generated.ts`, printCase(sources));
  }
  outputs.set(`${OUT_DIR}/index.generated.ts`, printIndex(ids, coverage));

  const outDir = join(root, OUT_DIR);
  const existing = existsSync(outDir) ? readdirSync(outDir).filter(f => f.endsWith('.generated.ts')) : [];
  const stale = existing.map(f => `${OUT_DIR}/${f}`).filter(path => !outputs.has(path));
  const changed = [...outputs].filter(([path, content]) => {
    const file = join(root, path);
    return !existsSync(file) || readFileSync(file, 'utf8') !== content;
  });

  if (write && errors.length === 0) {
    mkdirSync(outDir, { recursive: true });
    for (const [path, content] of changed) writeFileSync(join(root, path), content);
    for (const path of stale) rmSync(join(root, path));
  }
  return { ids, outputs, changed: changed.map(([path]) => path), stale, missing, errors, coverage };
}

function main(argv) {
  const check = argv.includes('--check');
  const complete = argv.includes('--complete');
  const unknown = argv.filter(a => a !== '--check' && a !== '--complete');
  if (unknown.length) {
    console.error(`gallery-sources: unknown argument ${unknown.join(' ')} (use --check and/or --complete)`);
    return 2;
  }
  const result = runGenerator({ write: !check });
  let failed = false;
  for (const error of result.errors) console.error(`✗ ${error}`);
  failed ||= result.errors.length > 0;

  if (check) {
    const outdated = [...result.changed, ...result.stale];
    if (outdated.length) {
      failed = true;
      console.error(`✗ gallery sources out of date (run \`pnpm gallery:sources\`):\n  ${outdated.join('\n  ')}`);
    }
  } else if (!failed) {
    const n = result.changed.length + result.stale.length;
    console.log(
      n
        ? `✓ gallery sources: ${result.changed.length} written, ${result.stale.length} removed`
        : '✓ gallery sources up to date',
    );
  }

  const total = result.ids.length * Object.keys(FRAMEWORK_TREES).length;
  const have = total - result.missing.length;
  if (complete && result.missing.length) {
    failed = true;
    // One line per case: `tree: react (TreeExample.tsx), vue (TreeExample.vue)`
    const byCase = new Map();
    for (const path of result.missing) {
      const [fw, id, file] = path.split('/');
      byCase.set(id, [...(byCase.get(id) ?? []), `${fw} (${file})`]);
    }
    const lines = [...byCase].map(([id, list]) => `${id}: ${list.join(', ')}`);
    console.error(`✗ ${result.missing.length} of ${total} case files missing:\n  ${lines.join('\n  ')}`);
  } else if (!failed) {
    console.log(
      `  ${have} of ${total} case files (${result.ids.length} cases × ${Object.keys(FRAMEWORK_TREES).length} frameworks)`,
    );
  }
  return failed ? 1 : 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
